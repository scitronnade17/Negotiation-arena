public static class ToneLibrary
{
    public static string Description(Tone tone)
    {
        switch (tone)
        {
            case Tone.Aggressive:
                return "Ты сразу переходишь в нападение, используешь резкие фразы, обвиняешь игрока, не терпишь воды и долгих вступлений.";
            case Tone.Friendly:
                return "Ты открыт к диалогу, используешь смягчающие фразы, обращаешься на \"вы\" с уважением, но твёрдо стоишь на своих интересах.";
            case Tone.Neutral:
                return "Ты общаешься исключительно сухими фактами, как робот. Никаких эмоций, только бизнес, цифры и логика.";
            case Tone.Sarcastic:
                return "Ты постоянно язвишь, используешь пассивную агрессию, иронизируешь над предложениями игрока и сомневаешься в его компетентности.";
            default:
                return "";
        }
    }
}
